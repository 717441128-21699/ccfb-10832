const map = new Map<string, string>()
const seenTrad = new Set<string>()
for (const [t, s] of PAIRS) {
  if (seenTrad.has(t)) continue
  seenTrad.add(t)
  if (t !== s) map.set(t, s)
}

/** 单字繁体转简体，未收录的字原样返回 */
export function tradToSimpleChar(ch: string): string {
  return map.get(ch) ?? ch
}

export function tradToSimple(text: string): string {
  let out = ''
  for (const ch of text) out += map.get(ch) ?? ch
  return out
}

/** 简体 -> 繁体 反向表（造数器把面单繁体化用） */
const reverseMap = new Map<string, string[]>()
for (const [t, s] of map) {
  const arr = reverseMap.get(s)
  if (arr) arr.push(t)
  else reverseMap.set(s, [t])
}

export function simpleToTradChar(ch: string): string | null {
  const arr = reverseMap.get(ch)
  return arr && arr.length ? arr[0] : null
}
